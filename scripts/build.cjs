const fs = require("node:fs");
const path = require("node:path");

const root = path.join(__dirname, "..");
const output = path.join(root, "interceptor-main.js");
const bundle = "// Generated by npm run build from profile-media.js and interceptor.js.\n" +
  ["profile-media.js", "interceptor.js"].map((file) => fs.readFileSync(path.join(root, file), "utf8").replace(/\r\n/g, "\n").trimEnd()).join("\n\n") + "\n";

if (process.argv.includes("--check")) {
  if (!fs.existsSync(output) || fs.readFileSync(output, "utf8").replace(/\r\n/g, "\n") !== bundle) {
    console.error("interceptor-main.js is outdated. Run npm run build.");
    process.exitCode = 1;
  }
} else {
  fs.writeFileSync(output, bundle);
}
